#!/system/bin/sh
#===============================================================================
# 清荷 - Magisk/KSU 模块卸载脚本
#===============================================================================

MODID=qinghe

echo ""
echo "====================================="
echo "  清荷 - 卸载"
echo "====================================="
echo ""
echo "数据目录: /data/$MODID/"
echo ""
echo "是否保留已备份的账号数据?"
echo "  [Y] 保留数据 (刷入新版本可继续使用)"
echo "  [N] 彻底删除所有数据"
echo ""
echo "注意: 默认选择保留, 10秒后自动确认"
echo "====================================="

echo -n "选择 [Y/n]: "
read -t 10 -r CHOICE

case "$CHOICE" in
    [Nn]*)
        echo ""
        echo "正在删除所有数据..."
        rm -rf /data/$MODID/ 2>/dev/null
        echo "数据已清除"
        ;;
    *)
        echo ""
        echo "数据已保留在 /data/$MODID/"
        echo "如需删除可手动执行: rm -rf /data/$MODID/"
        ;;
esac

echo ""
echo "卸载完成"
echo "====================================="
